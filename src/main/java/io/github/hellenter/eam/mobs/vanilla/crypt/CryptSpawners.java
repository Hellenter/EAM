package io.github.hellenter.eam.mobs.vanilla.crypt;

import io.github.hellenter.eam.Eam;

import net.minecraft.core.BlockPos;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.level.block.entity.trialspawner.TrialSpawner;
import net.minecraft.world.level.block.entity.trialspawner.TrialSpawnerConfig;
import net.minecraft.world.level.storage.loot.LootTable;
import net.minecraft.world.phys.Vec3;

/**
 * The crypt's trial spawners and the ancient metal gear their skeletons wear. All of it is data, generated by datagen:
 * {@code data/eam/trial_spawner/crypt/<mob>/{normal,ominous}.json} and {@code data/eam/loot_table/equipment/crypt/}.
 * <ul>
 * <li>swordsman (red wool): a skeleton with an ancient metal sword;</li>
 * <li>archer (yellow wool): a skeleton with a bow and ancient metal arrows;</li>
 * <li>knight (green wool): the {@code eam:skeleton_knight}, only 2 per spawner, 3 when ominous.</li>
 * </ul>
 * Swordsmen and archers wear a couple of armor pieces, always added in the order chestplate, helmet, boots, leggings,
 * nearly always ancient metal chainmail. An ominous spawner gives them more pieces, enchanted.
 * <p>
 * Crypt spawners wake up when a player they can see comes within {@link #ACTIVATION_RANGE} blocks (vanilla 14), spawn
 * mobs up to {@link #SPAWN_RANGE} blocks away to the sides (vanilla 4) and up to {@link #VERTICAL_RANGE} blocks up or
 * down (vanilla 1), on a floor.
 */
public final class CryptSpawners {
	public static final Spawner SWORDSMAN = new Spawner("swordsman");
	public static final Spawner ARCHER = new Spawner("archer");
	public static final Spawner KNIGHT = new Spawner("knight");

	public static final int ACTIVATION_RANGE = 24;
	public static final int SPAWN_RANGE = 7;
	public static final int VERTICAL_RANGE = 3;

	private CryptSpawners() {
	}

	/** A spawner runs a crypt config. */
	public static boolean isCrypt(TrialSpawner.FullConfig config) {
		return config.normal().unwrapKey()
				.map(key -> key.identifier().getNamespace().equals(Eam.MOD_ID) && key.identifier().getPath().startsWith("crypt/"))
				.orElse(false);
	}

	/** Moves a crypt mob's spawn spot onto a floor up to {@link #VERTICAL_RANGE} blocks above or below the spawner. */
	public static Vec3 spawnPos(ServerLevel level, BlockPos spawner, TrialSpawner.FullConfig config, Vec3 pos) {
		if (!isCrypt(config)) return pos;
		int startY = spawner.getY() + level.getRandom().nextIntBetweenInclusive(-VERTICAL_RANGE, VERTICAL_RANGE);
		BlockPos.MutableBlockPos at = new BlockPos.MutableBlockPos();
		int y = CryptSpawnerLogic.standingY(spawner.getY(), startY, VERTICAL_RANGE, height -> {
			at.set(pos.x, height, pos.z);
			if (!level.getBlockState(at).getCollisionShape(level, at).isEmpty()) return false;
			at.move(0, -1, 0);
			return !level.getBlockState(at).getCollisionShape(level, at).isEmpty();
		});
		return new Vec3(pos.x, y, pos.z);
	}

	/** One crypt spawner: its normal and ominous configs and the equipment tables they put on the mob. */
	public record Spawner(ResourceKey<TrialSpawnerConfig> normal, ResourceKey<TrialSpawnerConfig> ominous,
			ResourceKey<LootTable> gear, ResourceKey<LootTable> ominousGear) {
		Spawner(String name) {
			this(config(name + "/normal"), config(name + "/ominous"), gear(name), gear(name + "_ominous"));
		}

		private static ResourceKey<TrialSpawnerConfig> config(String path) {
			return ResourceKey.create(Registries.TRIAL_SPAWNER_CONFIG, Eam.id("crypt/" + path));
		}

		private static ResourceKey<LootTable> gear(String path) {
			return ResourceKey.create(Registries.LOOT_TABLE, Eam.id("equipment/crypt/" + path));
		}
	}
}
